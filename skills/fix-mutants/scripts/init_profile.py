#!/usr/bin/env python3
"""Detect a project's stack and write its fix-mutants profile into <repo>/.fix-mutants/.

Supported stacks (anything that emits a mutation-testing-elements JSON report):
  dotnet  Stryker.NET   — *.csproj with a test project referencing a production project
  js      StrykerJS     — package.json (JavaScript / TypeScript)
  generic Any other tool — writes a profile with TODO markers to fill in by hand

Standard library only. Re-run with --force to regenerate.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

SKIP_DIRS = {".git", "node_modules", "bin", "obj", "StrykerOutput", ".fix-mutants", "dist", "build", "reports"}

CSHARP_DECLARATIONS = r"\b(?:record(?:\s+(?:class|struct))?|class|struct|interface|enum)\s+(\w+)"
JS_DECLARATIONS = r"\b(?:class|function|interface|enum|type)\s+(\w+)"


def walk(root, pattern):
    for path in sorted(Path(root).rglob(pattern)):
        if not SKIP_DIRS.intersection(path.relative_to(root).parts):
            yield path


def detect_dotnet(repo, production=None, tests=None):
    projects = {path: path.read_text(encoding="utf-8-sig") for path in walk(repo, "*.csproj")}
    if not projects:
        return None
    test_projects = [p for p, text in projects.items() if "Microsoft.NET.Test.Sdk" in text]
    pairs = []
    for test in test_projects:
        for reference in re.findall(r'<ProjectReference\s+Include="([^"]+)"', projects[test]):
            target = (test.parent / reference.replace("\\", "/")).resolve()
            if target in projects and target not in test_projects:
                pairs.append((target, test))
    if production:
        pairs = [pair for pair in pairs if pair[0].parent.resolve() == (repo / production).resolve()]
    if tests:
        pairs = [pair for pair in pairs if pair[1].parent.resolve() == (repo / tests).resolve()]
    if not pairs:
        raise SystemExit("dotnet: no (production, test) project pair found; pass --production and --tests")
    prod, test = pairs[0]
    framework = next(
        (name for name in ("NUnit", "xunit", "MSTest") if name.lower() in projects[test].lower()), "unknown"
    )
    manifest = next(
        (m for m in walk(repo, "dotnet-tools.json") if "dotnet-stryker" in m.read_text(encoding="utf-8")), None
    )
    return {
        "stack": "dotnet",
        "production_root": prod.parent.relative_to(repo).as_posix(),
        "test_roots": [test.parent.relative_to(repo).as_posix()],
        "report_schema_version": "2",
        "declaration_pattern": CSHARP_DECLARATIONS,
        "_production_project": prod.name,
        "_test_project": test.name,
        "_test_framework": framework,
        "_stryker_installed": manifest is not None,
        "_alternatives": [
            f"{a.parent.relative_to(repo)} <- {b.parent.relative_to(repo)}" for a, b in pairs[1:]
        ],
    }


def detect_js(repo, production=None, tests=None):
    manifest = Path(repo) / "package.json"
    if not manifest.is_file():
        return None
    package = json.loads(manifest.read_text(encoding="utf-8"))
    dependencies = {**package.get("dependencies", {}), **package.get("devDependencies", {})}
    runner = next((name for name in ("jest", "vitest", "mocha", "karma", "jasmine") if name in dependencies), None)
    if runner is None and "@stryker-mutator/core" not in dependencies:
        return None
    source = production or next((d for d in ("src", "lib", "app") if (Path(repo) / d).is_dir()), ".")
    test_dirs = [tests] if tests else [d for d in ("test", "tests", "__tests__", "spec") if (Path(repo) / d).is_dir()]
    colocated = any(walk(Path(repo) / source, "*.test.*")) or any(walk(Path(repo) / source, "*.spec.*"))
    if colocated and source not in test_dirs:
        test_dirs.append(source)
    return {
        "stack": "js",
        "production_root": source,
        "test_roots": test_dirs or ["test"],
        "report_schema_version": "1.0",
        "declaration_pattern": JS_DECLARATIONS,
        "_test_framework": runner or "unknown",
        "_stryker_installed": "@stryker-mutator/core" in dependencies,
        "_typescript": "typescript" in dependencies,
    }


def generic(repo, production, tests):
    return {
        "stack": "generic",
        "production_root": production or "TODO/production/root",
        "test_roots": [tests or "TODO/test/root"],
        "report_schema_version": "2",
        "declaration_pattern": r"\b(?:class|struct|interface|enum|function|def|fn|trait)\s+(\w+)",
    }


