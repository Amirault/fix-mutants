def toplevel(repo):
    """Profile paths are relative to the git root, so a sub-folder of a monorepo works too."""
    try:
        out = subprocess.check_output(
            ["git", "rev-parse", "--show-toplevel"], cwd=repo, stderr=subprocess.DEVNULL, text=True
        )
        return Path(out.strip()).resolve()
    except (OSError, subprocess.CalledProcessError):
        return Path(repo)


def tests_pattern(test_roots):
    return "|".join(re.escape(root.rstrip("/")) + "/" for root in test_roots)


def render(detected, name, prefix=Path(".")):
    stack = detected["stack"]
    base = {"dotnet": DOTNET, "js": JS, "generic": GENERIC}[stack]
    values = dict(
        production_root=detected["production_root"],
        tests_pattern=tests_pattern(detected["test_roots"]),
        framework=detected.get("_test_framework", "unknown"),
        production_project=detected.get("_production_project", ""),
        test_project=detected.get("_test_project", ""),
        test_dir=detected["test_roots"][0],
        cd_line=f"cd {prefix.as_posix()}\n" if prefix != Path(".") else "",
        workdir_prefix=f"{prefix.as_posix()}/" if prefix != Path(".") else "",
        source_rel=Path(detected["production_root"]).relative_to(prefix).as_posix(),
    )
    parts = {key: value.format(**values) for key, value in base.items()}
    command_block = parts["command"]
    fenced = re.search(r"```bash\n(.*?)```", command_block, re.S)
    run = fenced.group(1).strip() if fenced else parts["command"]
    markdown = PROFILE_MD.format(
        name=name,
        tool=parts["tool"],
        tracker=(prefix / ".fix-mutants/MUTATION-TRACKING.md").as_posix(),
        fetch=(prefix / ".fix-mutants/report-fetch.md").as_posix(),
        production_root=detected["production_root"],
        test_roots=", ".join(f"`{root}`" for root in detected["test_roots"]),
        schema=detected["report_schema_version"],
        environment=parts["environment"],
        command=parts["command"],
        layers=parts["layers"],
        caller_search=parts["caller_search"],
        build_forced=parts["build_forced"],
        conventions=parts["conventions"],
    )
    fetch = REPORT_FETCH.format(command=run, report_glob=parts["report_glob"])
    return markdown, fetch


def main(argv=None):
    cli = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    cli.add_argument("--repo", default=".", help="repository root (default: .)")
    cli.add_argument("--stack", choices=("auto", "dotnet", "js", "generic"), default="auto")
    cli.add_argument("--production", help="production project/source folder, repo-relative (override detection)")
    cli.add_argument("--tests", help="test project/folder, repo-relative (override detection)")
    cli.add_argument("--dry-run", action="store_true", help="print the detection result, write nothing")
    cli.add_argument("--force", action="store_true", help="overwrite an existing .fix-mutants/")
    args = cli.parse_args(argv)
    repo = Path(args.repo).resolve()

    detected = None
    if args.stack in ("auto", "dotnet"):
        detected = detect_dotnet(repo, args.production, args.tests)
    if detected is None and args.stack in ("auto", "js"):
        detected = detect_js(repo, args.production, args.tests)
    if detected is None and args.stack == "generic":
        detected = generic(repo, args.production, args.tests)
    if detected is None:
        print(
            "init_profile: no supported stack detected (looked for .csproj test projects and package.json).\n"
            "Re-run with --stack generic to write a profile with TODOs, or see README → Other stacks.",
            file=sys.stderr,
        )
        return 2

    git_root = toplevel(repo)
    prefix = repo.relative_to(git_root)
    if prefix != Path("."):
        detected["production_root"] = (prefix / detected["production_root"]).as_posix()
        detected["test_roots"] = [(prefix / root).as_posix() for root in detected["test_roots"]]
    print(json.dumps({k: v for k, v in detected.items()}, indent=2))
    if args.dry_run:
        return 0

    target = repo / ".fix-mutants"
    if target.exists() and not args.force:
        print(f"init_profile: {target} exists; use --force to overwrite", file=sys.stderr)
        return 1
    target.mkdir(exist_ok=True)
    markdown, fetch = render(detected, repo.name, prefix)
    skill = Path(os.path.abspath(__file__)).parent.parent
    skill_ref = skill.relative_to(git_root).as_posix() if skill.is_relative_to(git_root) else "<skill>"
    profile_ref = (prefix / ".fix-mutants/profile.json").as_posix()
    markdown = markdown.replace("<skill>", skill_ref).replace("<profile>", profile_ref)
    fetch = fetch.replace("<skill>", skill_ref).replace("<profile>", profile_ref)
    profile = {k: v for k, v in detected.items() if not k.startswith("_") and k != "stack"}
    profile["gate_allow"] = [] if prefix == Path(".") else [(prefix / ".fix-mutants").as_posix()]
    (target / "profile.json").write_text(json.dumps(profile, indent=2) + "\n", encoding="utf-8")
    (target / "PROFILE.md").write_text(markdown, encoding="utf-8")
    (target / "report-fetch.md").write_text(fetch, encoding="utf-8")
    tracker = target / "MUTATION-TRACKING.md"
    if not tracker.exists():
        tracker.write_text(TRACKER, encoding="utf-8")
    print(f"\nWrote {target.relative_to(repo)}/ — review PROFILE.md (layers, conventions), then run the skill.")
    if detected.get("_alternatives"):
        print("Other (production <- test) pairs found, pass --production/--tests to pick one:")
        for pair in detected["_alternatives"]:
            print(f"  {pair}")
    if detected.get("_stryker_installed") is False:
        print("Note: Stryker is not installed in this project yet — see PROFILE.md → Environment setup.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
